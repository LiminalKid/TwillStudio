#!/usr/bin/env python3
"""Pre-render the UI fonts into antialiased glyph atlases, written as C++ source.

The device never parses font files: each (face, pixel size) becomes one 8-bit alpha atlas plus
per-glyph metrics, compiled into the app. Run this after changing faces or sizes:

    python3 tools/mkfonts.py

Needs Pillow (with FreeType). Writes src/gfx/gen/fonts.cpp.
"""
import os
import sys

from PIL import Image, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "third_party", "fonts", "inter")
OUT = os.path.join(ROOT, "src", "gfx", "gen", "fonts.cpp")

FACES = [  # (enum name, file)
    ("Regular", "Inter-Regular.ttf"),
    ("SemiBold", "Inter-SemiBold.ttf"),
]
PIXEL_SIZES = [12, 14, 16, 20, 24, 28, 32, 40]
FIRST, LAST = 32, 126  # printable ASCII
ATLAS_WIDTH = 512
PAD = 1


def render_face(path, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = font.getlength(ch)
        left, top, right, bottom = font.getbbox(ch)  # relative to the origin at the ascender line
        w, h = max(0, right - left), max(0, bottom - top)
        img = None
        if w and h:
            img = Image.new("L", (w, h), 0)
            img_draw_origin = (-left, -top)
            from PIL import ImageDraw
            ImageDraw.Draw(img).text(img_draw_origin, ch, font=font, fill=255)
        glyphs.append(dict(code=code, adv=advance, ox=left, oy=top - ascent, w=w, h=h, img=img))

    # Shelf-pack the glyphs into an atlas.
    x = y = shelf = 0
    for g in glyphs:
        if x + g["w"] + PAD > ATLAS_WIDTH:
            x, y, shelf = 0, y + shelf + PAD, 0
        g["ax"], g["ay"] = x, y
        x += g["w"] + PAD
        shelf = max(shelf, g["h"])
    height = y + shelf
    atlas = Image.new("L", (ATLAS_WIDTH, max(1, height)), 0)
    for g in glyphs:
        if g["img"] is not None:
            atlas.paste(g["img"], (g["ax"], g["ay"]))
    return dict(ascent=ascent, descent=descent, glyphs=glyphs, atlas=atlas)


def c_bytes(data):
    """Bytes as a C string literal body, broken into lines."""
    out, line = [], []
    for b in data:
        line.append("\\x%02x" % b)
        if len(line) == 64:
            out.append('"' + "".join(line) + '"')
            line = []
    if line:
        out.append('"' + "".join(line) + '"')
    return "\n    ".join(out) if out else '""'


def main():
    parts = [
        "// Generated by tools/mkfonts.py from Inter (SIL Open Font License 1.1, see",
        "// third_party/fonts/inter/LICENSE.txt). Do not edit.",
        '#include "gfx/Font.h"',
        "",
        "namespace twill {",
        "namespace {",
    ]
    table = []
    for face_name, file in FACES:
        path = os.path.join(FONT_DIR, file)
        for px in PIXEL_SIZES:
            f = render_face(path, px)
            ident = "%s_%d" % (face_name, px)
            parts.append("const GlyphInfo glyphs_%s[] = {" % ident)
            for g in f["glyphs"]:
                parts.append(
                    "  {%d, %d, %d, %d, %d, %d, %.3ff}," %
                    (g["ax"], g["ay"], g["w"], g["h"], g["ox"], g["oy"], g["adv"]))
            parts.append("};")
            atlas = f["atlas"]
            parts.append("const char atlas_%s[] =\n    %s;" % (ident, c_bytes(atlas.tobytes())))
            table.append(
                "  {FontFace::%s, %d, %d, %d, %d, %d, %d, %d, glyphs_%s, "
                "reinterpret_cast<const uint8_t*>(atlas_%s)}," %
                (face_name, px, f["ascent"], f["descent"], FIRST, LAST, atlas.width, atlas.height,
                 ident, ident))
    parts.append("}  // namespace")
    parts.append("")
    parts.append("const FontData kFonts[] = {")
    parts.extend(table)
    parts.append("};")
    parts.append("const int kNumFonts = %d;" % len(table))
    parts.append("")
    parts.append("}  // namespace twill")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("\n".join(parts) + "\n")
    print("wrote %s (%d fonts, %d KB)" % (OUT, len(table), os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    sys.exit(main())
